"""Turns the illustrator's character sheets (design/stepup/character/*.png, 4 x 2 cells of 512 px) into the app's sprites.
Usage: python3 scripts/make-character-sprites.py   (needs Pillow + numpy; a dev tool, not part of CI)
What it does: cleans the transparency (the generated sheets carry coloured halos and loose specks), keeps only the solid drawing, scales every frame by the
same factor, stands the feet on one baseline and centres the body, then writes
  web/art/character/walk.webp, run.webp         one strip per cycle: 8 frames of 256 x 256 side by side
  web/art/character/pose-<name>.webp            one picture per pose
  web/js/characterData.js                       what the app needs to know (frames, sizes, timing)
  design/stepup/character/qa-*.png              contact sheets on a light and a dark background, to look at before shipping."""
import json, sys
from collections import deque
from pathlib import Path
import numpy as np
from PIL import Image, ImageFilter

SRC = Path('design/stepup/character'); OUT = Path('web/art/character'); OUT.mkdir(parents=True, exist_ok=True)
CELL, FRAME, SCALE, BASE, SOLID, MIN_PART = 512, 256, 0.5, 246, 235, 500
CYCLES = {'walk': ('walk-cycle.png', 1200), 'run': ('run-cycle.png', 700)}
POSES = {'poses-1.png': ['idle', 'jump', 'cheer', 'wave', 'rest', 'stretch', 'medal', 'trophy'], 'poses-2.png': ['podium', 'point', 'think', 'sit', 'sleep', 'rain', None, None]}

def parts(mask):
    """8-connected components of a boolean mask -> list of (area, bool mask)."""
    h, w = mask.shape; seen = np.zeros_like(mask, bool); out = []
    for y0, x0 in zip(*np.nonzero(mask)):
        if seen[y0, x0]: continue
        q = deque([(y0, x0)]); seen[y0, x0] = True; pts = []
        while q:
            y, x = q.popleft(); pts.append((y, x))
            for dy in (-1, 0, 1):
                for dx in (-1, 0, 1):
                    yy, xx = y + dy, x + dx
                    if 0 <= yy < h and 0 <= xx < w and mask[yy, xx] and not seen[yy, xx]: seen[yy, xx] = True; q.append((yy, xx))
        if len(pts) >= MIN_PART:
            m = np.zeros_like(mask); ys, xs = zip(*pts); m[list(ys), list(xs)] = True; out.append((len(pts), m))
    return out

def clean(cell):
    """RGBA cell -> RGBA with only the solid drawing (no halo, no specks), edges feathered by one pixel."""
    a = np.array(cell); alpha = a[..., 3]
    keep = np.zeros(alpha.shape, bool)
    for _, m in parts(alpha >= SOLID): keep |= m
    if not keep.any(): return None
    k = Image.fromarray((keep * 255).astype('uint8')).filter(ImageFilter.MinFilter(3)).filter(ImageFilter.GaussianBlur(0.8))  # step into the outline, then soften
    a[..., 3] = np.minimum(alpha, np.array(k)); return Image.fromarray(a)

def place(img, scale, size, centre='mass'):
    """Scale, stand the feet on BASE and centre horizontally on the body's mass; shrink further only if it would not fit."""
    bb = img.getbbox(); img = img.crop(bb)
    s = scale
    if img.width * s > size - 12 or img.height * s > size - 12: s = min((size - 12) / img.width, (size - 12) / img.height)
    img = img.resize((max(1, round(img.width * s)), max(1, round(img.height * s))), Image.LANCZOS)
    al = np.array(img)[..., 3].astype(float); xs = np.nonzero(al.sum(0))[0]; cx = (al.sum(0) * np.arange(al.shape[1])).sum() / al.sum() if centre == 'mass' else (xs[0] + xs[-1]) / 2
    canvas = Image.new('RGBA', (size, size), (0, 0, 0, 0)); x = round(size / 2 - cx); y = min(BASE, size - 6) - img.height
    canvas.alpha_composite(img, (max(0, min(size - img.width, x)), max(0, y))); return canvas

def cells(sheet):
    im = Image.open(SRC / sheet).convert('RGBA'); return [im.crop(((i % 4) * CELL, (i // 4) * CELL, (i % 4 + 1) * CELL, (i // 4 + 1) * CELL)) for i in range(8)]

meta = {'cycles': {}, 'poses': {}}; qa = []
for name, (sheet, ms) in CYCLES.items():
    frames = [clean(c) for c in cells(sheet)]; assert all(f is not None for f in frames), name
    strip = Image.new('RGBA', (FRAME * 8, FRAME), (0, 0, 0, 0))
    for i, f in enumerate(frames): strip.alpha_composite(place(f, SCALE, FRAME), (i * FRAME, 0))
    strip.save(OUT / f'{name}.webp', 'WEBP', quality=84, alpha_quality=92, method=6); meta['cycles'][name] = {'file': f'art/character/{name}.webp', 'frames': 8, 'w': FRAME, 'h': FRAME, 'ms': ms}; qa.append((name, strip))
for sheet, names in POSES.items():
    for n, c in zip(names, cells(sheet)):
        if not n: continue
        f = clean(c); assert f is not None, n; size = 288
        p = place(f, SCALE, size); p.save(OUT / f'pose-{n}.webp', 'WEBP', quality=86, alpha_quality=92, method=6); meta['poses'][n] = {'file': f'art/character/pose-{n}.webp', 'w': size, 'h': size}; qa.append((n, p))
Path('web/js/characterData.js').write_text('// GENERATED by scripts/make-character-sprites.py from design/stepup/character/ - do not edit.\nexport const CHARACTER = ' + json.dumps(meta, indent=1) + ';\n')
for bg, col in (('light', (245, 248, 250, 255)), ('dark', (17, 24, 32, 255))):
    rows = [im for _, im in qa]; W = max(i.width for i in rows); sheet = Image.new('RGBA', (W, sum(i.height for i in rows)), col); y = 0
    for im in rows: sheet.alpha_composite(im, (0, y)); y += im.height
    sheet.convert('RGB').save(SRC / f'qa-{bg}.png')
print('walk/run strips, %d poses written' % len(meta['poses']))
