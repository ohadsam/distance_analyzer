"""Turns the illustrator's weather animation frames into the app's sprites (a dev tool, not part of CI; needs Pillow + numpy).
Usage: python3 scripts/make-weather-sprites.py <dir with wxa_<condition>_01..12.png> [<more dirs>...]
Each frame (512 px, flat magenta background) is keyed to transparency (the soft edge keeps its colour, the magenta fringe is removed), every frame of ALL
conditions is cropped to one common box and scaled by one factor, so the icons keep the same size and place, then one strip per condition is written:
  web/art/weather-anim/<condition>.webp   12 frames of 96 x 96 side by side
  web/js/weatherAnimData.js               the list of conditions and the strip geometry (generated; do not edit)
The originals' contact sheets are kept in design/stepup/weather-motion/."""
import sys, json
from pathlib import Path
import numpy as np
from PIL import Image

OUT = Path('web/art/weather-anim'); OUT.mkdir(parents=True, exist_ok=True)
FR, N, KEY = 96, 12, np.array([252, 4, 250], dtype=float)

def key_out(path):
    rgb = np.asarray(Image.open(path).convert('RGB')).astype(float)
    d = np.sqrt(((rgb - KEY) ** 2).sum(2))
    a = np.clip((d - 60) / 90, 0, 1)                       # 0 on the magenta, 1 on the drawing, soft in between
    # take the magenta out of the semi-transparent edge: c = (rgb - (1-a)*KEY) / a
    with np.errstate(divide='ignore', invalid='ignore'):
        c = np.where(a[..., None] > 0.02, (rgb - (1 - a[..., None]) * KEY) / np.maximum(a[..., None], 0.02), 0)
    return np.dstack([np.clip(c, 0, 255), a * 255]).astype(np.uint8)

conds = {}
for d in sys.argv[1:]:
    for p in sorted(Path(d).glob('wxa_*_[0-9][0-9].png')):
        name = p.stem.rsplit('_', 1)[0][4:]
        conds.setdefault(name, []).append(p)
if not conds: sys.exit('no frames found')
frames = {n: [key_out(p) for p in sorted(ps)] for n, ps in conds.items()}
assert all(len(v) == N for v in frames.values()), {n: len(v) for n, v in frames.items()}
# one common crop box over everything
x0 = y0 = 10 ** 9; x1 = y1 = -1
for fl in frames.values():
    for f in fl:
        ys, xs = np.where(f[..., 3] > 40)
        x0, x1, y0, y1 = min(x0, xs.min()), max(x1, xs.max()), min(y0, ys.min()), max(y1, ys.max())
side = max(x1 - x0, y1 - y0) + 8; cx, cy = (x0 + x1) // 2, (y0 + y1) // 2
box = (cx - side // 2, cy - side // 2, cx + side // 2, cy + side // 2)
for name, fl in sorted(frames.items()):
    strip = Image.new('RGBA', (FR * N, FR))
    for i, f in enumerate(fl):
        strip.paste(Image.fromarray(f, 'RGBA').crop(box).resize((FR, FR), Image.LANCZOS), (i * FR, 0))
    strip.save(OUT / f'{name}.webp', 'WEBP', quality=78, method=6)
    print(f'{name:22s} {(OUT / f"{name}.webp").stat().st_size // 1024} KB')
Path('web/js/weatherAnimData.js').write_text('// GENERATED by scripts/make-weather-sprites.py - do not edit.\nexport const WEATHER_ANIM = ' + json.dumps({'frames': N, 'size': FR, 'ms': 1800, 'conditions': sorted(frames)}) + ';\n')
