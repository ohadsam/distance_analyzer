"""Turns the rendered exercise frames into the app's sprites (a dev tool, not part of CI; needs Pillow + numpy).
Usage: python3 scripts/make-exercise-sprites.py <dir containing one folder per exercise id with ex_<id>_01..12_transparent.png>
Every frame of ALL exercises is cropped to one common box and scaled by one factor (the figure keeps its size and ground line), then one strip per exercise is written:
  web/art/exercises/<id>.webp   12 frames of 128 x 128 side by side
  web/js/exerciseData.js        the list of exercises with a picture and each one's loop time (from design/stepup/exercise-rig/loop_ms.json; generated, do not edit)
The frames come from design/stepup/exercise-rig/ (the character's parts, the rig and the pose scripts: python3 batch.py) and, for nine stretches, from the illustrator's own renders."""
import sys, json
from pathlib import Path
import numpy as np
from PIL import Image

OUT = Path('web/art/exercises'); OUT.mkdir(parents=True, exist_ok=True)
FR, N = 128, 12
MS = json.loads(Path('design/stepup/exercise-rig/loop_ms.json').read_text())
src = Path(sys.argv[1]); ids = sorted(p.name for p in src.iterdir() if p.is_dir())
frames = {i: [np.asarray(Image.open(src / i / f'ex_{i}_{k:02d}_transparent.png').convert('RGBA')) for k in range(1, N + 1)] for i in ids}
x0 = y0 = 10 ** 9; x1 = y1 = -1
for fl in frames.values():
    for f in fl:
        ys, xs = np.where(f[..., 3] > 40)
        x0, x1, y0, y1 = min(x0, xs.min()), max(x1, xs.max()), min(y0, ys.min()), max(y1, ys.max())
side = max(x1 - x0, y1 - y0) + 8; cx, cy = (x0 + x1) // 2, (y0 + y1) // 2
box = (cx - side // 2, cy - side // 2, cx + side // 2, cy + side // 2)
for i in ids:
    strip = Image.new('RGBA', (FR * N, FR))
    for k, f in enumerate(frames[i]):
        strip.paste(Image.fromarray(f, 'RGBA').crop(box).resize((FR, FR), Image.LANCZOS), (k * FR, 0))
    strip.save(OUT / f'{i}.webp', 'WEBP', quality=80, method=6)
    print(f'{i:18s} {(OUT / f"{i}.webp").stat().st_size // 1024} KB')
Path('web/js/exerciseData.js').write_text(
    '// GENERATED by scripts/make-exercise-sprites.py - do not edit. The exercises with a looping picture in web/art/exercises/<id>.webp (12 frames of 128 px side by side)\n'
    '// and each one\'s loop time in ms (a held stretch breathes slowly, a jog is quick). The screens show the character\'s stretch pose for an id that is not listed.\n'
    '// A unit test keeps this list and the files in step.\n'
    f'export const ANIMATED = {json.dumps(ids)};\n'
    f'export const EXERCISE_ANIM = {{ frames: {N}, size: {FR}, ms: 1500 }};\n'
    f'export const EXERCISE_MS = {json.dumps({i: MS[i] for i in ids})};\n')
